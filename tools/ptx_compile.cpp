/* Build-time helper (task 0097): compiles a CUDA file to PTX with NVRTC, CUDA's runtime compiler. NVRTC brings its own
 * headers and needs no host compiler, where nvcc runs the C++ compiler's own headers through CUDA's front end - and
 * CUDA 12.8's can't parse Visual Studio 2026's.
 *   ptx_compile <in.cu> <out.ptx> [-I<dir>...] [other NVRTC options...]
 * Task 0169 (ADR 0054): with --header=<path> it also writes the PTX as a C header to commit (the bytes, the FNV-1a 64
 * hash of every --hash-file=<path>'s text with its line ends as LF, and the OptiX version read from --optix-h=<path>);
 * tools/optix_ptx_embed.bat runs it, and a unit test checks the hash against the sources. */
#include <nvrtc.h>

#include <cstdio>
#include <cstdlib>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

/* FNV-1a 64 over a file's text with "\r\n" read as "\n" (core/hash.h's basis and prime). */
static bool hash_text(const std::string &path, unsigned long long &h) {
  std::ifstream f(path, std::ios::binary);
  if (!f) return false;
  std::stringstream ss;
  ss << f.rdbuf();
  for (char c : ss.str()) {
    if (c == '\r') continue;
    h ^= (unsigned char)c;
    h *= 0x100000001b3ull;
  }
  return true;
}
/* OPTIX_VERSION's number from optix.h (0 when not found). */
static long optix_version(const std::string &path) {
  std::ifstream f(path);
  for (std::string line; std::getline(f, line);) {
    const size_t at = line.find("#define OPTIX_VERSION ");
    if (at != std::string::npos) return std::atol(line.c_str() + at + 22);
  }
  return 0;
}
static int write_header(const std::string &path, const char *ptx, size_t len, const std::vector<std::string> &files, const std::string &optix_h) {
  unsigned long long h = 0xcbf29ce484222325ull;
  for (const std::string &f : files)
    if (!hash_text(f, h)) {
      std::fprintf(stderr, "ptx_compile: can't read %s\n", f.c_str());
      return 1;
    }
  std::ofstream o(path, std::ios::binary);
  o << "// SPDX-License-Identifier: GPL-2.0-or-later\n"
       "// Generated by tools/optix_ptx_embed.bat (tasks 0169-0170, ADR 0054) from src/render/optix_kernel.cu and the GPU path\n"
       "// tracer's GLSL (translated by tools/glsl_to_cuda.py): the OptiX kernel as PTX, built into Blendity so a build needs\n"
       "// only OptiX's host headers. Do not edit: run the tool again after changing them (a unit test compares the hash\n"
       "// below with the sources). The PTX is text, in pieces under MSVC's string-literal limit, joined at run time.\n"
       "#pragma once\n";
  char line[200];
  std::snprintf(line, sizeof(line), "#define BL_OPTIX_PTX_SOURCE_HASH 0x%016llxull\n#define BL_OPTIX_PTX_OPTIX_VERSION %ld\n#define BL_OPTIX_PTX_BYTES %zu\n", h,
                optix_version(optix_h), len);
  o << line << "static const char *const optix_kernel_ptx_parts[] = {\n";
  /* Pieces of whole lines, each under 15,000 bytes, as raw string literals (PTX has no ")PTX" + '"' in it). */
  size_t at = 0;
  while (at < len) {
    size_t end = at, cut = at;
    while (end < len && end - at < 15000) {
      if (ptx[end] == '\n') cut = end + 1;
      end++;
    }
    if (end >= len) cut = len;
    if (cut == at) cut = end;  // (a line longer than a piece: cut it anyway)
    o << "R\"PTX(";
    o.write(ptx + at, (std::streamsize)(cut - at));
    o << ")PTX\",\n";
    at = cut;
  }
  o << "};\n";
  return o ? 0 : 1;
}

int main(int argc, char **argv) {
  if (argc < 3) {
    std::fprintf(stderr, "usage: ptx_compile <in.cu> <out.ptx> [options...]\n");
    return 2;
  }
  std::ifstream in(argv[1], std::ios::binary);
  std::stringstream src;
  src << in.rdbuf();
  if (!in) {
    std::fprintf(stderr, "ptx_compile: can't read %s\n", argv[1]);
    return 1;
  }
  nvrtcProgram prog;
  if (nvrtcCreateProgram(&prog, src.str().c_str(), argv[1], 0, nullptr, nullptr) != NVRTC_SUCCESS) return 1;
  std::vector<const char *> opts;
  std::string header, optix_h;
  std::vector<std::string> hash_files;
  for (int a = 3; a < argc; a++) {
    const std::string s = argv[a];
    if (s.rfind("--header=", 0) == 0) header = s.substr(9);
    else if (s.rfind("--hash-file=", 0) == 0) hash_files.push_back(s.substr(12));
    else if (s.rfind("--optix-h=", 0) == 0) optix_h = s.substr(10);
    else opts.push_back(argv[a]);
  }
  const nvrtcResult r = nvrtcCompileProgram(prog, (int)opts.size(), opts.data());
  size_t log_size = 0;
  nvrtcGetProgramLogSize(prog, &log_size);
  if (log_size > 1) {
    std::string log(log_size, '\0');
    nvrtcGetProgramLog(prog, &log[0]);
    std::fprintf(stderr, "%s\n", log.c_str());
  }
  if (r != NVRTC_SUCCESS) return 1;
  size_t n = 0;
  nvrtcGetPTXSize(prog, &n);
  std::string ptx(n, '\0');
  nvrtcGetPTX(prog, &ptx[0]);
  nvrtcDestroyProgram(&prog);
  const size_t len = n > 0 && ptx[n - 1] == '\0' ? n - 1 : n;
  std::ofstream out(argv[2], std::ios::binary);
  out.write(ptx.data(), (std::streamsize)len);
  if (!out) return 1;
  return header.empty() ? 0 : write_header(header, ptx.data(), len, hash_files, optix_h);
}
