MeshPtr teapot(float height, int res) {
  auto m = std::make_shared<Mesh>();
  m->name = "Teapot";
  res = std::max(2, res);
  const float s = height / 3.15f;  // Newell's teapot is 3.15 units tall
  /* Weld the patches' shared borders (and the points the lid's knob and the
   * bottom collapse to) through a hash of rounded positions. */
  std::unordered_map<uint64_t, uint32_t> weld;
  const float q = 1e4f / std::max(1e-6f, height);
  auto vert = [&](Vec3 p) {
    const int64_t x = std::llround(p.x * q), y = std::llround(p.y * q), z = std::llround(p.z * q);
    const uint64_t key = ((uint64_t)(x & 0x1fffff) << 42) | ((uint64_t)(y & 0x1fffff) << 21) | (uint64_t)(z & 0x1fffff);
    auto it = weld.find(key);
    if (it != weld.end()) return it->second;
    const uint32_t i = m->add_vert(p);
    weld.emplace(key, i);
    return i;
  };
  for (int pi = 0; pi < 32; pi++) {
    Vec3 cp[16];
    for (int k = 0; k < 16; k++) {
      const float *c = kTeapotVerts[kTeapotPatches[pi][k]];
      cp[k] = Vec3(c[0], c[2], -c[1]) * s;  // z-up to y-up
    }
    std::vector<uint32_t> grid((res + 1) * (res + 1));
    for (int i = 0; i <= res; i++)
      for (int j = 0; j <= res; j++) grid[i * (res + 1) + j] = vert(bezier_patch(cp, (float)i / res, (float)j / res));
    /* Each patch gets its own cell of an 8 x 4 UV atlas. */
    const Vec2 cell((pi % 8) / 8.0f, (pi / 8) / 4.0f);
    for (int i = 0; i < res; i++)
      for (int j = 0; j < res; j++) {
        /* Newell's patches face inward (u x v): walk v first so faces point out. */
        const int ij[4][2] = {{i, j}, {i, j + 1}, {i + 1, j + 1}, {i + 1, j}};
        uint32_t f[4];
        Vec2 uv[4];
        int n = 0;
        for (int c = 0; c < 4; c++) {
          const uint32_t vi = grid[ij[c][0] * (res + 1) + ij[c][1]];
          if (n && (f[n - 1] == vi || (c == 3 && f[0] == vi))) continue;
          uv[n] = cell + Vec2(ij[c][0] / (8.0f * res), ij[c][1] / (4.0f * res)) * 0.96f + Vec2(0.0025f, 0.0025f);
          f[n++] = vi;
        }
        if (n >= 3 && f[n - 1] == f[0]) n--;
        if (n < 3) continue;
        m->add_face(f, n, uv);
      }
  }
  m->smooth = true;
  m->touch();
  return m;
}

