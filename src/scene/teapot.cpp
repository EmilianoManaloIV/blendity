Vec3 bezier_patch(const Vec3 *cp, float u, float v) {
  auto bern = [](float t, float b[4]) {
    const float s = 1.0f - t;
    b[0] = s * s * s, b[1] = 3 * t * s * s, b[2] = 3 * t * t * s, b[3] = t * t * t;
  };
  float bu[4], bv[4];
  bern(u, bu);
  bern(v, bv);
  Vec3 p(0.0f);
  for (int i = 0; i < 4; i++)
    for (int j = 0; j < 4; j++) p += cp[i * 4 + j] * (bu[i] * bv[j]);
  return p;
}

